# src/llm/ollama_provider.py
"""
voxi — LLM Module (Local via Ollama)
Handles all communication with the local Ollama server.
"""

import json
from typing import Generator, Optional
import requests

from src.config.settings import (
    OLLAMA_MODEL,
    OLLAMA_BASE_URL,
    SYSTEM_PROMPT,
)


class OllamaProvider:
    """Connects to local Ollama server for LLM inference."""

    def __init__(self) -> None:
        """Initialize the Ollama LLM provider and verify connectivity."""
        self.model: str = OLLAMA_MODEL
        self.base_url: str = OLLAMA_BASE_URL
        self._check_connection()
        print(f"✅ Ollama LLM connected — Model: {self.model}")

    def _check_connection(self) -> None:
        """Verify Ollama server is running and accessible."""
        try:
            response = requests.get(
                f"{self.base_url}/api/tags",
                timeout=5
            )
            if response.status_code != 200:
                raise RuntimeError(f"Ollama returned HTTP status {response.status_code}")

            # Verify target model is installed
            models = response.json().get("models", [])
            model_names = [m.get("name", "") for m in models]
            if not any(self.model in name for name in model_names):
                print(f"   ⚠️ Model '{self.model}' not found in Ollama.")
                print(f"   Available models: {model_names}")
                print(f"   👉 Run: ollama pull {self.model}")

        except requests.exceptions.ConnectionError:
            raise ConnectionError(
                "❌ Ollama is not running!\n"
                "   👉 Fix: Open a terminal and run 'ollama serve'"
            )
        except Exception as e:
            raise RuntimeError(f"❌ Ollama connection failed: {e}")

    def generate(self, user_message: str, history: Optional[list[dict[str, str]]] = None) -> str:
        """
        Get a complete (non-streaming) response from the LLM.

        Args:
            user_message: User query string.
            history: Optional conversation history message list.

        Returns:
            str: Assistant response text.
        """
        messages = self._build_messages(user_message, history)

        try:
            response = requests.post(
                f"{self.base_url}/api/chat",
                json={
                    "model": self.model,
                    "messages": messages,
                    "stream": False,
                    "think": False,
                    "options": {
                        "temperature": 0.7,
                        "num_predict": 200,
                    }
                },
                timeout=60
            )
            if response.status_code == 200:
                result = response.json()
                return result.get("message", {}).get("content", "")
            return f"⚠️ Ollama error: HTTP {response.status_code}"
        except requests.exceptions.RequestException as e:
            return f"⚠️ LLM connection error: {e}"

    def generate_stream(
        self, user_message: str, history: Optional[list[dict[str, str]]] = None
    ) -> Generator[str, None, None]:
        """
        Stream response tokens from Ollama as they are generated.

        Args:
            user_message: User query string.
            history: Optional conversation history message list.

        Yields:
            str: Next token generated by the model.
        """
        messages = self._build_messages(user_message, history)

        try:
            with requests.post(
                f"{self.base_url}/api/chat",
                json={
                    "model": self.model,
                    "messages": messages,
                    "stream": True,
                    "think": False,
                    "options": {
                        "temperature": 0.7,
                        "num_predict": 200,
                    }
                },
                stream=True,
                timeout=60
            ) as response:
                for line in response.iter_lines():
                    if line:
                        chunk = json.loads(line)
                        if not chunk.get("done", False):
                            token = chunk.get("message", {}).get("content", "")
                            if token:
                                yield token
        except requests.exceptions.RequestException as e:
            print(f"   ⚠️ Streaming error: {e}")

    def _build_messages(
        self, user_message: str, history: Optional[list[dict[str, str]]] = None
    ) -> list[dict[str, str]]:
        """
        Build message payload with system prompt, history, and user input.

        Args:
            user_message: Current user message.
            history: Prior conversation turns.

        Returns:
            list[dict[str, str]]: Complete message list.
        """
        messages: list[dict[str, str]] = [
            {"role": "system", "content": SYSTEM_PROMPT}
        ]

        if history:
            messages.extend(history)

        messages.append({
            "role": "user",
            "content": user_message
        })

        return messages
