# src/main.py
"""
voxi — Main Entry Point
Integrates STT, LLM, TTS, and Memory into an end-to-end Voice Assistant.
"""

import argparse
import os
import sys
from typing import Generator

# Add root directory to sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))

from src.config.settings import ASSISTANT_NAME
from src.llm.ollama_provider import OllamaProvider
from src.memory.conversation_memory import ConversationMemory
from src.stt.whisper_stt import WhisperSTT
from src.tts.basic_tts import BasicTTS


class VoiceAssistant:
    """Main Voice Assistant orchestrator."""

    def __init__(self) -> None:
        """Initialize all sub-modules and display startup banner."""
        self._print_banner()

        print("🚀 Initializing components...")
        self.stt: WhisperSTT = WhisperSTT()
        self.llm: OllamaProvider = OllamaProvider()
        self.tts: BasicTTS = BasicTTS()
        self.memory: ConversationMemory = ConversationMemory()

        print("\n✨ All components loaded successfully!\n")

    def _print_banner(self) -> None:
        """Display startup banner."""
        banner = f"""
============================================================
                     🎙️✨ {ASSISTANT_NAME}
          "your voice, your device, your data."
============================================================
"""
        print(banner)

    def process_input_streaming(self, user_input: str) -> Generator[str, None, None]:
        """
        Process user text, yield streaming tokens from LLM, and update memory.

        Args:
            user_input: Message from user.

        Yields:
            str: Next token generated by LLM.
        """
        self.memory.add_user_message(user_input)

        full_response: str = ""
        for token in self.llm.generate_stream(user_input, history=self.memory.get_history()):
            full_response += token
            yield token

        if full_response.strip():
            self.memory.add_assistant_message(full_response.strip())

    def run_voice_mode(self) -> None:
        """Run full hands-free interactive voice loop with mic and speaker."""
        print("=" * 50)
        print("🎤 VOICE MODE ACTIVE")
        print("   Speak into your microphone. Say 'exit', 'quit', or 'bye' to quit.")
        print("   Say 'clear' to reset conversation memory.")
        print("=" * 50)

        greeting: str = f"Hi, I'm {ASSISTANT_NAME}. How can I help you?"
        self.tts.speak(greeting)

        while True:
            try:
                user_text: str = self.stt.listen_and_transcribe()
                if not user_text:
                    continue

                cleaned_input: str = user_text.lower().strip(" .,!?:;")

                if cleaned_input in ["exit", "quit", "bye", "goodbye"]:
                    farewell: str = "Goodbye! Have a great day."
                    print(f"\n👋 {farewell}")
                    self.tts.speak(farewell)
                    break

                if cleaned_input == "clear":
                    self.memory.clear()
                    confirmation: str = "I've cleared our conversation memory."
                    print(f"\n🔄 {confirmation}")
                    self.tts.speak(confirmation)
                    continue

                print(f"\n🤖 {ASSISTANT_NAME}: ", end="", flush=True)
                token_stream = self.process_input_streaming(user_text)
                self.tts.speak_streaming(token_stream)

            except KeyboardInterrupt:
                print("\n\n⏹️ Voice assistant stopped by user.")
                break
            except Exception as e:
                error_msg: str = "Sorry, I ran into an issue processing that."
                print(f"\n❌ Error: {e}")
                try:
                    self.tts.speak(error_msg)
                except Exception:
                    pass

    def run_text_mode(self) -> None:
        """Run text-only terminal interaction mode without mic or TTS."""
        print("=" * 50)
        print("💬 TEXT MODE ACTIVE (No Mic, No TTS)")
        print("   Type your message. Type 'exit' to quit, 'clear' to reset memory.")
        print("=" * 50)

        print(f"\n🤖 {ASSISTANT_NAME}: Hi, I'm {ASSISTANT_NAME}. How can I help you?")

        while True:
            try:
                user_input: str = input("\n👤 You: ").strip()
                if not user_input:
                    continue

                cleaned_input: str = user_input.lower().strip(" .,!?:;")

                if cleaned_input in ["exit", "quit", "bye", "goodbye"]:
                    print("\n👋 Goodbye! Have a great day.")
                    break

                if cleaned_input == "clear":
                    self.memory.clear()
                    print("🔄 Conversation memory cleared.")
                    continue

                print(f"\n🤖 {ASSISTANT_NAME}: ", end="", flush=True)
                for token in self.process_input_streaming(user_input):
                    print(token, end="", flush=True)
                print()

            except KeyboardInterrupt:
                print("\n\n⏹️ Session ended.")
                break
            except Exception as e:
                print(f"\n❌ Error: {e}")


def main() -> None:
    """Main CLI entrypoint."""
    parser = argparse.ArgumentParser(
        prog="voxi",
        description="🎙️✨ voxi — your voice, your device, your data. Fully local AI voice assistant.",
    )
    parser.add_argument(
        "--text",
        action="store_true",
        help="Run in interactive text mode (keyboard input, text response)",
    )
    args = parser.parse_args()

    assistant = VoiceAssistant()

    if args.text:
        assistant.run_text_mode()
    else:
        assistant.run_voice_mode()


if __name__ == "__main__":
    main()
